# 빠른 조회용 인덱스
BY_CODE: dict[str, Category] = {c.code: c for c in CATEGORIES}
BY_NAME: dict[str, Category] = {c.name: c for c in CATEGORIES}

FALLBACK: Category = BY_CODE["etc"]

NAMES: tuple[str, ...] = tuple(c.name for c in CATEGORIES)


def get(name_or_code: str) -> Category:
    """이름('국토교통') 또는 코드('land_transport') 로 카테고리를 찾습니다. 없으면 '기타'."""
    key = (name_or_code or "").strip()
    return BY_NAME.get(key) or BY_CODE.get(key.lower()) or FALLBACK


def prompt_block() -> str:
    """⑤ Qwen 프롬프트에 넣는 '카테고리 정의(7종)' 블록."""
    lines = ["[카테고리 정의 - 7종]"]
    for c in CATEGORIES:
        lines.append(f"- {c.name}({c.department}): {c.summary}")
    return "\n".join(lines)
